import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest

SCRIPTS = Path(__file__).resolve().parents[1]


class ScopeTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.repo = self.root / 'repo'
        self.repo.mkdir()
        self.run_cmd('git', 'init', '-q')
        self.run_cmd('git', 'config', 'user.name', 'Test')
        self.run_cmd('git', 'config', 'user.email', 'test@example.com')
        self.original = '// old client comment\n' + 'int stable = 1;\n' * 20
        (self.repo / 'code.cs').write_text(self.original)
        self.commit()
        self.base = self.run_cmd('git', 'rev-parse', 'HEAD').stdout.strip()
        (self.repo / 'code.cs').write_text(self.original + '// Generated by AI\nint fresh = 2;\n')
        (self.repo / 'new.md').write_text('New documentation\n')
        self.commit()
        self.changed = self.root / 'changed.txt'
        self.changed.write_text('code.cs\nnew.md\n')
        self.scope = self.root / 'scope'
        self.scope.mkdir()

    def run_cmd(self, *args, **kwargs):
        return subprocess.run(args, cwd=self.repo, text=True, capture_output=True, check=True, **kwargs)

    def commit(self):
        self.run_cmd('git', 'add', '.')
        self.run_cmd('git', 'commit', '-qm', 'fixture')

    def prepare(self):
        self.run_cmd('python3', str(SCRIPTS / 'ai_diff_scope.py'), 'prepare', self.base,
                     str(self.changed), str(self.scope))

    def test_only_diff_exposed_and_client_lines_preserved(self):
        self.prepare()
        workspace = self.scope / 'fragments'
        self.assertNotIn('old client comment', (workspace / 'context.json').read_text())
        self.assertEqual((workspace / '000000.cs').read_text(), '// Generated by AI\nint fresh = 2;\n')
        self.assertEqual((workspace / '000001.md').read_text(), 'New documentation\n')
        (workspace / '000000.cs').write_text('int fresh = 2;\n')
        self.run_cmd('python3', str(SCRIPTS / 'ai_diff_scope.py'), 'apply', str(self.scope))
        self.assertEqual((self.repo / 'code.cs').read_text(), self.original + 'int fresh = 2;\n')

    def test_replacement_blocks_deletion_and_no_final_newline(self):
        (self.repo / 'code.cs').write_text('// client comment\nint stable = 1;\n// removed\nint end = 2;')
        self.commit()
        base = self.run_cmd('git', 'rev-parse', 'HEAD').stdout.strip()
        (self.repo / 'code.cs').write_text('// replacement comment\nint stable = 1;\nint end = 2;')
        self.commit()
        self.changed.write_text('code.cs\n')
        self.run_cmd('python3', str(SCRIPTS / 'ai_diff_scope.py'), 'prepare', base,
                     str(self.changed), str(self.scope))
        fragments = list((self.scope / 'fragments').glob('*.cs'))
        self.assertEqual(len(fragments), 1)
        self.assertEqual(fragments[0].read_text(), '// replacement comment\n')
        fragments[0].write_text('// concise\n')
        self.run_cmd('python3', str(SCRIPTS / 'ai_diff_scope.py'), 'apply', str(self.scope))
        self.assertEqual((self.repo / 'code.cs').read_bytes(), b'// concise\nint stable = 1;\nint end = 2;')

    def test_comment_only_cleanup_does_not_expose_file_to_ai(self):
        # Cleanup leaves whitespace where source-only comments used to be.
        (self.repo / 'code.cs').write_text(self.original + '                 \n')
        self.commit()
        self.changed.write_text('code.cs\n')
        self.prepare()
        self.assertEqual(json.loads((self.scope / 'manifest.json').read_text())['entries'], [])
        self.assertEqual(json.loads((self.scope / 'fragments/context.json').read_text()), [])

    def test_context_tampering_rejected(self):
        self.prepare()
        (self.scope / 'fragments/context.json').write_text('[]')
        with self.assertRaises(subprocess.CalledProcessError):
            self.run_cmd('python3', str(SCRIPTS / 'ai_diff_scope.py'), 'apply', str(self.scope))
        self.assertEqual(self.run_cmd('git', 'diff').stdout, '')

    def test_cleanup_pipeline_and_code_guard(self):
        fakebin = self.root / 'bin'
        fakebin.mkdir()
        fake = fakebin / 'codex'
        fake.write_text('''#!/usr/bin/env python3
import json, os
from pathlib import Path
p = Path('000000.cs')
s = p.read_text().replace('// Generated by AI\\n', '')
if os.environ.get('BAD_EDIT'):
    s = s.replace('fresh = 2', 'fresh = 999')
p.write_text(s)
print(json.dumps({'type': 'turn.completed', 'usage': {}}))
''')
        fake.chmod(0o755)
        for bad in ('', 'yes'):
            with self.subTest(bad=bad):
                self.run_cmd('git', 'restore', '.')
                status = self.root / 'status.env'
                status.write_text('')
                env = dict(os.environ, PATH=str(fakebin) + os.pathsep + os.environ['PATH'],
                           AI_ENGINE='codex', BAD_EDIT=bad, RUNNER_TEMP=str(self.root), GITHUB_ENV=str(status), AI_STRICT='true')
                self.run_cmd('bash', str(SCRIPTS / 'ai_cleanup.sh'), str(self.changed),
                             str(SCRIPTS / 'ai-cleanup-prompt.md'), str(SCRIPTS / 'check_ai_diff.py'), self.base, env=env)
                if bad:
                    self.assertEqual(self.run_cmd('git', 'diff').stdout, '')
                    self.assertIn('AI đổi cả dòng code', status.read_text())
                else:
                    self.assertEqual((self.repo / 'code.cs').read_text(), self.original + 'int fresh = 2;\n')
                    self.assertIn('AI đã dọn', status.read_text())


if __name__ == '__main__':
    unittest.main()
