#!/usr/bin/env python3
"""Run a synthetic local sync and export a condensed, assertion-backed demo transcript."""
import ast
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

project = Path(__file__).resolve().parents[1]
jar = Path(os.environ['COPYBARA_JAR']).resolve()
root = Path(tempfile.mkdtemp(prefix='release-sync-demo-'))
env = os.environ.copy()

def run(*args, cwd=None):
    result = subprocess.run(args, cwd=cwd, env=env, text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(result.stdout + result.stderr)
    return result.stdout

for name in ('source', 'client'):
    repo = root / name
    repo.mkdir()
    run('git', 'init', '-q', '-b', 'main', cwd=repo)
    run('git', 'config', 'user.name', 'Demo', cwd=repo)
    run('git', 'config', 'user.email', 'demo@example.com', cwd=repo)
    value = 2 if name == 'source' else 1
    comment = '// Generated by AI\n' if name == 'source' else ''
    (repo / 'App.cs').write_text(comment + f'class App {{ int Value = {value}; }}\n')
    if name == 'source':
        (repo / 'CLAUDE.md').write_text('Internal agent instructions\n')
        (repo / '.cursor').mkdir()
        (repo / '.cursor/rules.md').write_text('Internal workspace rules\n')
    else:
        (repo / 'client-only.txt').write_text('Keep this client-owned file.\n')
    run('git', 'add', '.', cwd=repo)
    run('git', 'commit', '-qm', 'Demo fixture', cwd=repo)
config = (project / '.copybara/copy.bara.sky').read_text()
node = next(n for n in ast.parse(config).body if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id == 'REPOS')
repos = [dict(name='demo', source_url=(root/'source').as_uri(), source_ref='main', dest_url=(root/'client').as_uri(), dest_base='main')]
lines = config.splitlines(keepends=True)
config_file = root/'copy.bara.sky'
config_file.write_text(''.join(lines[:node.lineno-1])+'REPOS = '+json.dumps(repos)+'\n'+''.join(lines[node.end_lineno:]))
cache = root/'cache'; cache.mkdir()
shutil.copy(jar, cache/'copybara_deploy-v20260907.jar')
env.update(CONFIG=str(config_file), SYNC_HOME=str(cache), COPYBARA_VERSION='v20260907', JAVA_TOOL_OPTIONS='-Duser.home='+str(root/'java'))
log = run('bash', str(project/'.copybara/sync-local.sh'), 'demo', '--squash', cwd=project)
(root/'sync.log').write_text(log)
review = next(cache.glob('demo-*/review'))
assert not (review/'CLAUDE.md').exists()
assert not (review/'.cursor').exists()
assert (review/'client-only.txt').read_text() == 'Keep this client-owned file.\n'
assert '// Generated by AI' not in (review/'App.cs').read_text()
assert 'Value = 2' in (review/'App.cs').read_text()
assert 'Value = 1' in run('git','show','main:App.cs',cwd=root/'client')
diff = run('git', 'diff', '--no-color', 'origin/main..HEAD', '--', 'App.cs', cwd=review)
frames = [
 {'title':'1 / 5  Development workspace', 'lines':['$ ls -a source/', 'App.cs  CLAUDE.md  .cursor/', '', '// Generated by AI', 'class App { int Value = 2; }', '', 'Client repo also has client-only.txt']},
 {'title':'2 / 5  Run a local release', 'lines':['$ ./.copybara/sync-local.sh demo --squash', '', 'Copybara migration completed', 'Destination-only file restored', 'New C# comment removed', 'No AI provider called', 'Local review branch created']},
 {'title':'3 / 5  Verify the handoff', 'lines':['Assertions against the generated release:', '', 'PASS  CLAUDE.md not imported', 'PASS  .cursor/ not imported', 'PASS  client-only.txt preserved', 'PASS  new comment removed', 'PASS  application change retained']},
 {'title':'4 / 5  Review the actual diff', 'lines':['$ git diff origin/main..HEAD -- App.cs', '', *diff.strip().splitlines()[-7:]]},
 {'title':'5 / 5  Publish is a separate action', 'lines':['Client main still contains: Value = 1', '', 'Review code + edit release notes first.', '', 'When ready:', '$ ./.copybara/sync-local.sh demo --push', '', 'This demo does NOT push or create a PR.']},
]
out = project/'docs/demo'; out.mkdir(parents=True, exist_ok=True)
(out/'transcript.json').write_text(json.dumps(frames, indent=2))
print('PASS: actual local sync, file filtering, comment cleanup, client preservation, and no remote publish')
print('Wrote docs/demo/transcript.json; full logs kept in temporary directory:', root)
